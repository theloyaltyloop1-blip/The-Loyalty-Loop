"""Writes the approved Whirl (small variant, light theme) as app-ready modules.
Run after build.py: python brand/mascot/src/export_app.py
 - apps/shopper/src/mascot-whirl.ts and apps/retailer/src/mascot-whirl.ts: SVG strings for react-native-svg SvgXml
 - apps/web/public/mascot/whirl-<pose>.svg (+ dark/)
"""
import json, pathlib, shutil
R = pathlib.Path(__file__).resolve().parents[3]
poses = ['wave', 'stamp', 'celebrate', 'sleepy', 'think', 'thumbs']
svg = R / 'brand/mascot/svg'
data = {p: (svg / f'whirl-small-{p}.svg').read_text(encoding='utf-8') for p in poses}
dark = {p: (svg / 'dark' / f'whirl-small-{p}.svg').read_text(encoding='utf-8') for p in poses}
body = ('// Generated by brand/mascot/src/export_app.py. Do not edit by hand.\n'
        'export type WhirlPose = ' + ' | '.join(json.dumps(p) for p in poses) + '\n'
        'export const WHIRL_XML: Record<WhirlPose, string> = ' + json.dumps(data, indent=2) + '\n'
        'export const WHIRL_XML_DARK: Record<WhirlPose, string> = ' + json.dumps(dark, indent=2) + '\n')
for app in ('shopper', 'retailer'):
    (R / f'apps/{app}/src/mascot-whirl.ts').write_text(body, encoding='utf-8')
for sub in ('', 'dark'):
    d = R / 'apps/web/public/mascot' / sub
    d.mkdir(parents=True, exist_ok=True)
    for p in poses:
        shutil.copy(svg / sub / f'whirl-small-{p}.svg', d / f'whirl-{p}.svg')
print('ok')

// Runs actual admin source against test-only in-memory auth/data aliases.
const { createRequire } = require('node:module')
const path = require('node:path')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const { pathToFileURL } = require('node:url')
const root = path.resolve(__dirname, '..')
const fixture = path.join(__dirname, 'admin-reference-preview')
const { chromium } = createRequire(path.join(process.argv[2], 'package.json'))('playwright')
const out = path.join(root, 'tmp/deletion-ui')
fs.mkdirSync(out, { recursive: true })
;(async () => {
  const { createServer } = await import(pathToFileURL(path.join(root, 'apps/web/node_modules/vite/dist/node/index.js')))
  const { default: react } = await import(pathToFileURL(path.join(root, 'apps/web/node_modules/@vitejs/plugin-react/dist/index.js')))
  const { default: tailwindcss } = await import(pathToFileURL(path.join(root, 'apps/web/node_modules/@tailwindcss/vite/dist/index.mjs')))
  const server = await createServer({ configFile: false, root: fixture, plugins: [{ name: 'fixture-relative-supabase', enforce: 'pre', resolveId(source, importer) { if (source === './supabase' && importer?.replaceAll('\\', '/').includes('/apps/web/src/lib/')) return path.join(fixture, 'supabase.ts') } }, react(), tailwindcss()],
    resolve: { dedupe: ['react', 'react-dom'], alias: [ { find: 'react-router-dom', replacement: path.join(root, 'apps/web/node_modules/react-router-dom/dist/index.mjs') }, { find: '@/lib/supabase', replacement: path.join(fixture, 'supabase.ts') }, { find: '@/lib/auth-context', replacement: path.join(fixture, 'auth.tsx') }, { find: '@', replacement: path.join(root, 'apps/web/src') } ] },
    define: { 'import.meta.env.VITE_SUPABASE_URL': JSON.stringify('https://fixture.invalid'), 'import.meta.env.VITE_SUPABASE_ANON_KEY': JSON.stringify('fixture-only') },
    server: { host: '127.0.0.1', port: 4182, strictPort: true, fs: { allow: [root] } } })
  await server.listen()
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const page = await browser.newPage({ reducedMotion: 'reduce' })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
    const base = 'http://127.0.0.1:4182/access?view=businesses&fixture=deletion'
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(base)
    await page.getByRole('button', { name: 'Delete shop', exact: true }).click()
    const confirm = page.getByRole('button', { name: 'Delete shop permanently', exact: true })
    assert.equal(await confirm.isDisabled(), true)
    await page.getByRole('textbox', { name: 'Confirm shop name' }).fill('Wrong name')
    assert.equal(await confirm.isDisabled(), true)
    await page.getByRole('textbox', { name: 'Confirm shop name' }).fill('Marlow Street Coffee')
    assert.equal(await confirm.isEnabled(), true)
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.equal(await page.getByLabel('Confirm shop deletion').count(), 0)
    assert.equal(await page.evaluate(() => window.deletionCall ?? null), null)
    await page.getByRole('button', { name: 'Delete shop', exact: true }).click()
    assert.equal(await confirm.isDisabled(), true)
    await page.getByRole('textbox', { name: 'Confirm shop name' }).fill('Marlow Street Coffee')
    await page.evaluate(() => { window.deletionFail = true })
    await confirm.click()
    await page.getByText('Fixture deletion refused', { exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Delete shop', exact: true }).count(), 1)
    await page.evaluate(() => { window.deletionFail = false })
    await confirm.click()
    await page.getByText('Shop permanently deleted', { exact: true }).waitFor()
    assert.deepEqual(await page.evaluate(() => window.deletionCall), { body: { business_id: 'shop-1', confirmation_name: 'Marlow Street Coffee' } })
    assert.equal(await page.getByRole('button', { name: 'Delete shop', exact: true }).count(), 0)
    assert.deepEqual(errors, [])
    console.log('Admin deletion mock browser checks passed: exact-name gate, cancel, refusal, success, payload and refreshed rows. No network mutations.')
  } finally { await browser.close(); await server.close() }
})().catch(error => { console.error(error); process.exit(1) })

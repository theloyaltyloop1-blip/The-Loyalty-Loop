// Runs actual admin source against test-only in-memory auth/data aliases.
const { createRequire } = require('node:module')
const path = require('node:path')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const { pathToFileURL } = require('node:url')
const root = path.resolve(__dirname, '..')
const fixture = path.join(__dirname, 'admin-reference-preview')
const { chromium } = createRequire(path.join(process.argv[2], 'package.json'))('playwright')
const out = path.join(root, 'docs/design/admin-reference')
fs.mkdirSync(out, { recursive: true })
;(async () => {
  const { createServer } = await import(pathToFileURL(path.join(root, 'apps/web/node_modules/vite/dist/node/index.js')))
  const { default: react } = await import(pathToFileURL(path.join(root, 'apps/web/node_modules/@vitejs/plugin-react/dist/index.js')))
  const { default: tailwindcss } = await import(pathToFileURL(path.join(root, 'apps/web/node_modules/@tailwindcss/vite/dist/index.mjs')))
  const server = await createServer({ configFile: false, root: fixture, plugins: [{ name: 'fixture-relative-supabase', enforce: 'pre', resolveId(source, importer) { if (source === './supabase' && importer?.replaceAll('\\', '/').includes('/apps/web/src/lib/')) return path.join(fixture, 'supabase.ts') } }, react(), tailwindcss()],
    resolve: { dedupe: ['react', 'react-dom'], alias: [ { find: 'react-router-dom', replacement: path.join(root, 'apps/web/node_modules/react-router-dom/dist/index.mjs') }, { find: '@/lib/supabase', replacement: path.join(fixture, 'supabase.ts') }, { find: '@/lib/auth-context', replacement: path.join(fixture, 'auth.tsx') }, { find: '@', replacement: path.join(root, 'apps/web/src') } ] },
    define: { 'import.meta.env.VITE_SUPABASE_URL': JSON.stringify('https://fixture.invalid'), 'import.meta.env.VITE_SUPABASE_ANON_KEY': JSON.stringify('fixture-only') },
    server: { host: '127.0.0.1', port: 4182, strictPort: true, fs: { allow: [root] } } })
  await server.listen()
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const page = await browser.newPage({ reducedMotion: 'reduce' })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
    const base = 'http://127.0.0.1:4182/access'
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(base)
    await page.getByRole('heading', { name: 'Most used features' }).waitFor()
    await page.evaluate(() => document.fonts.ready)
    assert.equal(await page.getByRole('navigation').getByRole('button').count(), 14)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.screenshot({ path: path.join(out, 'overview-desktop.png'), fullPage: true })
    await page.getByRole('button', { name: 'People per feature', exact: true }).click()
    await page.getByText('Unique people within each feature and surface', { exact: true }).waitFor()
    assert.equal(await page.getByText('2,695', { exact: true }).count(), 1)
    await page.getByRole('navigation').getByRole('button', { name: 'Trending shops' }).click()
    await page.getByRole('heading', { name: 'Trending shops' }).first().waitFor()
    assert.match(page.url(), /view=trending/)
    await page.reload()
    await page.getByRole('heading', { name: 'Trending shops' }).first().waitFor()
    await page.getByRole('navigation').getByRole('button', { name: 'Shop requests' }).click()
    await page.getByRole('heading', { name: 'Shop requests' }).first().waitFor()
    await page.goBack()
    await page.getByRole('heading', { name: 'Trending shops' }).first().waitFor()
    for (const name of ['Users & roles', 'All businesses', 'Loyalty data', 'Audit log', 'Platform controls', 'Business listings', 'Owner support', 'Reported reviews', 'Laptop backups', 'Paused features', 'Product analytics']) {
      await page.getByRole('navigation').getByRole('button', { name, exact: false }).click()
      await page.getByRole('heading', { name, exact: true }).first().waitFor()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, name + ' overflow')
    }
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(base)
    await page.getByRole('heading', { name: 'Most used features' }).waitFor()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.screenshot({ path: path.join(out, 'overview-mobile.png'), fullPage: true })
    await page.addInitScript(() => localStorage.setItem('loyalty-loop-theme', 'dark'))
    await page.goto(base)
    await page.getByRole('heading', { name: 'Most used features' }).waitFor()
    assert.equal(await page.locator('.admin-panel').evaluate(el => getComputedStyle(el).getPropertyValue('--color-primary').trim()), '#272331')
    await page.goto(base + '?fixture=empty')
    await page.getByText('No activity yet').first().waitFor()
    assert.equal(await page.locator('.admin-donut').count(), 0)
    await page.goto(base + '?fixture=analytics-error')
    await page.getByRole('heading', { name: 'Analytics unavailable' }).waitFor()
    assert.equal(await page.locator('.admin-donut').count(), 0)
    await page.goto(base + '?fixture=queues-error')
    await page.getByText('Could not load', { exact: true }).waitFor()
    assert.deepEqual(errors, [])
    fs.writeFileSync(path.join(out, 'results.json'), JSON.stringify({ passed: ['14 views retained', 'desktop/mobile no overflow', 'measure toggle and unchanged app total', 'URL/reload/back', 'all admin views render', 'global dark isolation', 'empty analytics', 'failed analytics without charts', 'failed queue unavailable'], pageErrors: errors, data: 'Illustrative mock values only; no live account or provider request.' }, null, 2))
    console.log('Admin reference browser checks passed; illustrative fixture data only.')
  } finally { await browser.close(); await server.close() }
})().catch(error => { console.error(error); process.exit(1) })
